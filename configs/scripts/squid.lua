-- Fake Squid HTTP forward proxy (handler: lua, port 3128). An open proxy is a
-- prime abuse target — attackers test CONNECT / absolute-URI GET to relay mail,
-- IRC C2, or scanning through someone else's IP. We capture what they tried to
-- reach and REFUSE; nothing is ever relayed (no amplification / no SSRF).
--
-- Demonstrates: request parsing, header capture, abuse flagging, engagement.

local reqline = conn:readline() or ""
local method, target = reqline:match("^(%u+)%s+(%S+)")
meta("request_line", (reqline:gsub("[\r\n]", "")))

for _ = 1, 40 do
  local h = conn:readline()
  if not h or h == "\r\n" or h == "\n" then break end
  if string.lower(h):find("^proxy%-authorization:") then
    meta("proxy_authorization", (h:gsub("[\r\n]", "")))
    flag("proxy-auth-attempt")
  end
end

method = method or ""
if method == "CONNECT" then
  meta("connect_target", target or "")
  flag("open-proxy-connect")          -- TLS tunnel attempt through us
elseif target and target:find("^https?://") then
  meta("proxy_target", target)
  flag("open-proxy-request")          -- absolute-URI = treating us as a proxy
end

local body = "<html><head><title>ERROR: The requested URL could not be retrieved</title></head>" ..
  "<body><h1>ERROR</h1><p>The following error was encountered while trying to retrieve the URL.</p>" ..
  "<p><b>Access Denied.</b></p><hr><address>Generated by squid/5.7</address></body></html>"
conn:write("HTTP/1.1 403 Forbidden\r\nServer: squid/5.7\r\nMime-Version: 1.0\r\n" ..
  "Content-Type: text/html;charset=utf-8\r\nX-Squid-Error: ERR_ACCESS_DENIED 0\r\n" ..
  "Content-Length: " .. tostring(#body) .. "\r\nConnection: close\r\n\r\n" .. body)
