package decoygen

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// GenOptions controls how a scan Result is turned into a config.
type GenOptions struct {
	Bind        string // bind address for the generated listeners (e.g. "0.0.0.0")
	Archetype   string // optional sensor.archetype to stamp
	SensorName  string // optional sensor.name
	ReadTimeout string // per-listener read_timeout (e.g. "30s")
}

// genConfig is the minimal config shape we emit — sensor + listeners only.
// It deliberately mirrors the real config schema (internal/config) so the
// output drops straight into tarpit-honeypot, but stays small and reviewable.
type genConfig struct {
	Sensor    *genSensor     `yaml:"sensor,omitempty"`
	Listeners []*genListener `yaml:"listeners"`
}

type genSensor struct {
	Name      string `yaml:"name,omitempty"`
	Archetype string `yaml:"archetype,omitempty"`
}

type genListener struct {
	ID          string  `yaml:"id"`
	Proto       string  `yaml:"proto"`
	Bind        string  `yaml:"bind"`
	Handler     string  `yaml:"handler"`
	Severity    string  `yaml:"severity,omitempty"`
	ReadTimeout string  `yaml:"read_timeout,omitempty"`
	HTTPS       *genTLS `yaml:"https,omitempty"`
}

type genTLS struct {
	CN string `yaml:"cn,omitempty"`
}

// portPlan is the de-duplicated decision for one port across all hosts.
type portPlan struct {
	port    int
	handler string
	tls     bool
	certCN  string
	banner  string
	hosts   int
}

// plan collapses the per-host services into one listener per port, picking the
// most common handler seen on that port (a honeypot is a single host that
// presents the union of the environment's service ports).
func plan(services []Service) []portPlan {
	type agg struct {
		handlerVotes map[string]int
		tls          bool
		certCN       string
		banner       string
		hosts        int
	}
	byPort := map[int]*agg{}
	for _, s := range services {
		a := byPort[s.Port]
		if a == nil {
			a = &agg{handlerVotes: map[string]int{}}
			byPort[s.Port] = a
		}
		a.hosts++
		if s.Handler != "" {
			a.handlerVotes[s.Handler]++
		}
		if s.TLS {
			a.tls = true
		}
		if a.certCN == "" && s.CertCN != "" {
			a.certCN = s.CertCN
		}
		if a.banner == "" && s.Banner != "" {
			a.banner = s.Banner
		}
	}
	var plans []portPlan
	for port, a := range byPort {
		// Pick the winning handler (most votes; ties broken by name for
		// determinism).
		best, bestN := "auto", -1
		for h, n := range a.handlerVotes {
			if n > bestN || (n == bestN && h < best) {
				best, bestN = h, n
			}
		}
		plans = append(plans, portPlan{
			port: port, handler: best, tls: a.tls,
			certCN: a.certCN, banner: a.banner, hosts: a.hosts,
		})
	}
	sort.Slice(plans, func(i, j int) bool { return plans[i].port < plans[j].port })
	return plans
}

// Generate turns a scan Result into a reviewable YAML config (a header comment
// + sensor + one listener per discovered port). It never returns an error for
// an empty result — it emits a config with no listeners and an explanatory
// header so the operator sees the scan ran.
func Generate(res Result, opts GenOptions) (string, error) {
	bind := opts.Bind
	if bind == "" {
		bind = "0.0.0.0"
	}
	rt := opts.ReadTimeout
	if rt == "" {
		rt = "30s"
	}

	plans := plan(res.Services)

	cfg := genConfig{}
	if opts.SensorName != "" || opts.Archetype != "" {
		cfg.Sensor = &genSensor{Name: opts.SensorName, Archetype: opts.Archetype}
	}
	idSeen := map[string]int{}
	for _, p := range plans {
		svc := serviceLabel(p.port, p.handler)
		id := svc
		if idSeen[id] > 0 { // shouldn't happen (one per port) but stay safe
			id = fmt.Sprintf("%s-%d", svc, p.port)
		}
		idSeen[id]++
		l := &genListener{
			ID:          id,
			Proto:       "tcp",
			Bind:        joinHostPort(bind, p.port),
			Handler:     p.handler,
			Severity:    "medium",
			ReadTimeout: rt,
		}
		if p.certCN != "" && (p.handler == "https" || p.handler == "imaps" || p.handler == "pop3s" || p.handler == "ldaps") {
			l.HTTPS = &genTLS{CN: p.certCN}
		}
		cfg.Listeners = append(cfg.Listeners, l)
	}

	body, err := yaml.Marshal(cfg)
	if err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString("# tarpit-honeypot config generated by `generate-decoys`.\n")
	b.WriteString(fmt.Sprintf("# Scanned %d host(s), %d port-probes; found %d open service(s) on %d distinct port(s).\n",
		res.Hosts, res.Ports, len(res.Services), len(plans)))
	b.WriteString("#\n")
	b.WriteString("# REVIEW BEFORE USE. This mirrors the live services discovered so the\n")
	b.WriteString("# honeypot blends into the environment. Adjust binds, severities, and\n")
	b.WriteString("# archetypes, add an archetype for identity coherence, and wire your\n")
	b.WriteString("# sinks/UI before deploying. Generated listeners are TCP connect-decoys.\n")
	if len(plans) > 0 {
		b.WriteString("#\n# Per-port evidence:\n")
		for _, p := range plans {
			line := fmt.Sprintf("#   %d/tcp -> %s  (%d host(s)", p.port, p.handler, p.hosts)
			if p.certCN != "" {
				line += ", cert CN: " + p.certCN
			} else if p.banner != "" {
				line += ", banner: " + p.banner
			}
			line += ")\n"
			b.WriteString(line)
		}
	}
	b.WriteString("\n")
	b.Write(body)
	return b.String(), nil
}

// joinHostPort joins a bind address and port, bracketing IPv6 literals.
func joinHostPort(bind string, port int) string {
	if strings.Contains(bind, ":") && !strings.HasPrefix(bind, "[") {
		bind = "[" + bind + "]"
	}
	return bind + ":" + strconv.Itoa(port)
}

// serviceLabel builds a stable, readable listener id like "tcp-ssh-22".
func serviceLabel(port int, handler string) string {
	h := handler
	if h == "" {
		h = "svc"
	}
	return fmt.Sprintf("tcp-%s-%d", h, port)
}
